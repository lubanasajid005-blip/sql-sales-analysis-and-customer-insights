-- Magnitude Analysis

-- find the total customer by countries
select country,
count(customer_key) as total_customer
from dbo.dim_customers
group by country
order by total_customer desc

--find the toal customer by gender
select gender ,
count(customer_key) as total_customer
from dbo.dim_customers
group by gender
order by total_customer desc

--find the total products by category
select category,
count(product_key) as total_products
from dbo.dim_products
group by category
order by total_products desc

-- find the average cost in each category
select category,
avg(cost) as avg_cost
from dbo.dim_products
group by category
order by avg_cost desc

--what is the revenue generated for each category?
select 
p.category,
sum(f.sales_amount) total_revenue
from dbo.fact_sales f
left join dbo.dim_products p
on p.product_key= f.product_key
group by p.category
order by total_revenue desc

--what is the total revenue generated by each customer
select 
c.customer_key,
c.first_name,
c.last_name,
sum(f.sales_amount) as total_revenue
from dbo.fact_sales f
left join dbo.dim_customers c
on c.customer_key=f.customer_key
group by
c.customer_key,
c.first_name,
c.last_name
order by total_revenue desc

-- what is the total distribution of sold items across countries
select 
c.country,
sum(f.quantity) as total_sold_items
from dbo.fact_sales f
left join dbo.dim_customers c
on c.customer_key=f.customer_key
group by
c.country
order by total_sold_items desc

-- Ranking Analysis

--Which 5 products generate the highest revenue?

select top 5
p.product_name,
sum(f.sales_amount) as total_revenue
from dbo.fact_sales f
left join dbo.dim_products p
on p.product_key=p.product_key
group by p.product_name
order by total_revenue desc

select * 
from(
     select 
     p.product_name,
     row_number() over (order by sum(f.sales_amount)desc) as rank_products
     from dbo.fact_sales f
     left join dbo.dim_products p
     on p.product_key=p.product_key
     group by p.product_name)t
where rank_products <=5

-- find the top 10 customers who have generated the highest revenue
select top 10
c.customer_key,
